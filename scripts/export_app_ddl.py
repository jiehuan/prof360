"""Write SQL Server DDL for the application tables the pipeline writes (decisions D-037).

    python scripts/export_app_ddl.py

- deploy/sql/app_schema_changes.sql: what the team's data model diagram needs (new tables,
  added columns, indexes, foreign keys to drop). Idempotent: every statement checks first.
- deploy/sql/app_schema_full.sql: CREATE TABLE for every table in schema_app.py, for reference
  and for new environments.
Generated from src/uw_pipeline/schema_app.py; rerun after changing it and commit the output.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from sqlalchemy import Column, Table
from sqlalchemy.dialects import mssql
from sqlalchemy.schema import CreateIndex, CreateTable

from uw_pipeline.schema_app import app_metadata

OUT = Path(__file__).resolve().parents[1] / "deploy" / "sql"

# Phase 9 changes to the diagram (docs/schema-contract.md).
NEW_TABLES = ["ItemLink", "CompanyMetricDetail", "pipeline_publish_map"]
ADDED_COLUMNS = {
    "KeyInsights": ["isActive"],
    "FollowUpQuestions": ["Priority", "isActive"],
    "LoanTypes": ["ParentSegment"],
    "LoanPortfolio": ["PeriodEnd", "PctOfBook", "Nonaccrual", "NonaccrualRatio"],
    "NewsRiskScore": ["ActivityId"],
    "TranscriptRiskFlag": ["Category"],
    "TranscriptToneAnalysis": ["CompanyId", "Quarter"],
}
# Columns whose foreign key pointed to a table the pipeline replaced (not built any more).
REPLACED_REFERENCES = ["alpha_Transcripts", "alpha_run", "alpha_NewsArticle"]

# SQL Server 2019 / Azure SQL: DATE, and NVARCHAR(max) instead of the deprecated NTEXT.
DIALECT: Any = mssql.dialect(deprecate_large_types=True)  # type: ignore[no-untyped-call]
DIALECT.server_version_info = (15,)
Q = DIALECT.identifier_preparer.quote

HEADER = """-- Generated by scripts/export_app_ddl.py from src/uw_pipeline/schema_app.py.
-- Do not edit; change schema_app.py and regenerate. Target: Azure SQL / SQL Server 2019+.
-- Background: docs/schema-contract.md and docs/decisions.md (D-037).
"""


def _type(col: Column[object]) -> str:
    return str(DIALECT.type_compiler_instance.process(col.type))


def _add_column(table: Table, name: str) -> str:
    col = table.c[name]
    t, c = Q(table.name), Q(name)
    if name == "isActive":
        # Existing rows are the current versions.
        spec = f"BIT NOT NULL CONSTRAINT {Q(f'DF_{table.name}_isActive')} DEFAULT 1"
    else:
        # Added as NULL so existing rows stay valid; the pipeline fills every new row.
        spec = f"{_type(col)} NULL"
    return (f"IF COL_LENGTH(N'{table.name}', N'{name}') IS NULL\n"
            f"    ALTER TABLE {t} ADD {c} {spec};\nGO")  # fmt: skip


def _create(table: Table) -> str:
    ddl = str(CreateTable(table).compile(dialect=DIALECT)).strip()
    return f"IF OBJECT_ID(N'{table.name}', N'U') IS NULL\n{ddl};\nGO"


def _indexes(table: Table) -> list[str]:
    out = []
    for ix in sorted(table.indexes, key=lambda i: i.name or ""):
        ddl = str(CreateIndex(ix).compile(dialect=DIALECT)).strip()
        out.append(f"IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'{ix.name}' "
                   f"AND object_id = OBJECT_ID(N'{table.name}'))\n    {ddl};\nGO")  # fmt: skip
    return out


def changes() -> str:
    t = app_metadata.tables
    parts = [HEADER, "-- Changes to the team's data model diagram for the pipeline (Phase 9).",
             "-- Safe to run more than once.", ""]  # fmt: skip
    parts += ["-- 1. New tables ------------------------------------------------------------", ""]
    for name in NEW_TABLES:
        doc = {
            "ItemLink": "Every Related tab: links between key insights, strategic risks, "
            "follow-up questions and metrics; read from either end.",
            "CompanyMetricDetail": "Metric modal (and the Loan Portfolio modal as metric "
            "'loan_portfolio'): methodology, data sources, data points, UW relevance.",
            "pipeline_publish_map": "Pipeline bookkeeping (pipeline object -> app id); "
            "written and read only by the pipeline.",
        }[name]
        parts += [f"-- {name}: {doc}", _create(t[name]), *_indexes(t[name]), ""]
    parts += ["-- 2. Added columns ----------------------------------------------------------", ""]
    for name, cols in ADDED_COLUMNS.items():
        parts += [f"-- {name}"] + [_add_column(t[name], c) for c in cols] + [""]
    parts += ["-- 3. Indexes for the BFF's reads ---------------------------------------------", ""]
    for name in sorted(ADDED_COLUMNS):
        parts += _indexes(t[name])
    parts += [
        "",
        "-- 4. Foreign keys to tables the pipeline replaced -------------------------------",
        "-- " + ", ".join(REPLACED_REFERENCES) + " are no longer built. Columns that referenced",
        "-- them (TranscriptsId, runId, News.ArticleId) now hold pipeline ids: transcript document",
        "-- id, pipeline run id and news article id. Drop those foreign keys. List them with:",
        "--",
        "-- SELECT fk.name AS constraint_name, OBJECT_NAME(fk.parent_object_id) AS table_name,",
        "--        OBJECT_NAME(fk.referenced_object_id) AS referenced_table",
        "-- FROM sys.foreign_keys fk",
        "-- WHERE OBJECT_NAME(fk.referenced_object_id) IN ("
        + ", ".join(f"N'{r}'" for r in REPLACED_REFERENCES)
        + ");",
        "--",
        "-- then for each row: ALTER TABLE [<table_name>] DROP CONSTRAINT [<constraint_name>];",
        "",
        "-- 5. Content format (no DDL) ----------------------------------------------------",
        "-- Sources columns (KeyInsights.source, StrategicRisk.sources, Activities.sources,",
        "-- FollowUpQuestions.sources, Trend.DataSources, CompanyMetricDetail.DataSources) hold",
        '-- JSON: [{"title": "...", "url": "...", "date": "YYYY-MM-DD"}]. KeyInsights.link is the',
        "-- first url. MatrixData.accession, filed_date and context_or_dimension hold JSON lists.",
        "",
    ]
    return "\n".join(parts)


def full() -> str:
    parts = [HEADER, "-- Every table the pipeline writes, in dependency order. Tables owned by the",
             "-- application (Users, UserHistory, ...) are not included.", ""]  # fmt: skip
    for table in app_metadata.sorted_tables:
        parts += [_create(table), *_indexes(table), ""]
    return "\n".join(parts)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in (("app_schema_changes.sql", changes()), ("app_schema_full.sql", full())):
        (OUT / name).write_text(text, encoding="utf-8")
        print(f"wrote deploy/sql/{name}")


if __name__ == "__main__":
    main()
