"""Write SQL Server DDL for the tables the pipeline uses (decisions D-037, D-040).

    python scripts/export_app_ddl.py

- deploy/sql/app_schema_changes.sql: what the team's data model diagram needs (new tables,
  added columns, indexes, foreign keys to drop). Idempotent: every statement checks first.
- deploy/sql/app_schema_full.sql: CREATE TABLE for every table in schema_app.py.
- deploy/sql/pipeline_schema_full.sql: the pipeline's own tables (schema.py).
Tables are qualified with the schemas in config/azure.yaml (default environment). Generated from
the table definitions, in their definition order, so a rerun without changes gives the same
files; rerun after changing the tables or the schema names, and commit the output.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from sqlalchemy import Column, MetaData, Table
from sqlalchemy.dialects import mssql
from sqlalchemy.schema import CreateIndex, CreateTable, DDLElement

from uw_pipeline.clients.db import load_azure_config
from uw_pipeline.schema import metadata as pipeline_metadata
from uw_pipeline.schema_app import app_metadata

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "deploy" / "sql"

# Changes to the diagram (docs/schema-contract.md): Phase 9, and KeyTakeaways (2026-10-20).
NEW_TABLES = ["ItemLink", "CompanyMetricDetail", "KeyTakeaways", "pipeline_publish_map"]
ADDED_COLUMNS = {
    "KeyInsights": ["isActive"],
    "FollowUpQuestions": ["Priority", "isActive"],
    "LoanTypes": ["ParentSegment"],
    "LoanPortfolio": ["PeriodEnd", "PctOfBook", "Nonaccrual", "NonaccrualRatio"],
    "NewsRiskScore": ["ActivityId"],
    "TranscriptRiskFlag": ["Category"],
    "TranscriptToneAnalysis": ["CompanyId", "Quarter"],
}
# Columns added to pipeline tables after they were first deployed; the full pipeline script
# adds them to an existing table (CREATE TABLE ... IF missing does not).
PIPELINE_ADDED_COLUMNS = {
    "board_composition": [
        "fees_fiscal_year",
        "audit_fees",
        "audit_related_fees",
        "tax_fees",
        "other_fees",
        "dual_class",
        "ceo_name",
        "ceo_since",
    ],  # Phase 15f
}
# Columns whose foreign key pointed to a table the pipeline replaced (not built any more).
REPLACED_REFERENCES = ["alpha_Transcripts", "alpha_run", "alpha_NewsArticle"]
TABLE_DOCS = {
    "ItemLink": "Every Related tab: links between key insights, strategic risks, follow-up "
    "questions and metrics; read from either end.",
    "CompanyMetricDetail": "Metric modal (and the Loan Portfolio modal as metric "
    "'loan_portfolio'): methodology, data sources, data points, UW relevance.",
    "KeyTakeaways": "Key Takeaway box above Key Insights: 2-3 bullets for professional lines, "
    "most important first (Ordinal 1), no links; read isActive = 1.",
    "pipeline_publish_map": "Pipeline bookkeeping (pipeline object -> app id); written and read "
    "only by the pipeline.",
}

# SQL Server 2019 / Azure SQL: DATE, and NVARCHAR(max) instead of the deprecated NTEXT.
DIALECT: Any = mssql.dialect(deprecate_large_types=True)  # type: ignore[no-untyped-call]
DIALECT.server_version_info = (15,)
Q = DIALECT.identifier_preparer.quote

_AZ = load_azure_config(ROOT / "config")
_ENV = _AZ.azure_sql.environments[_AZ.default_env]
APP_SCHEMA, PIPELINE_SCHEMA = _ENV.app_schema, _ENV.pipeline_schema

HEADER = f"""-- Generated by scripts/export_app_ddl.py from schema_app.py and schema.py.
-- Do not edit; change the table definitions or config/azure.yaml and regenerate.
-- Target: Azure SQL / SQL Server 2019+. Background: docs/schema-contract.md, D-037, D-040.
-- Schemas (config/azure.yaml, {_AZ.default_env}): app tables in [{APP_SCHEMA}], pipeline
-- tables in [{PIPELINE_SCHEMA}].
"""


def _compile(ddl: DDLElement, schema: str) -> str:
    """`ddl` with the (schema-less) tables placed in `schema`, foreign key targets included.
    Compiled from the original tables, not copies: a copy's constraints come out in a random
    order, and every regeneration would show a diff."""
    return str(ddl.compile(dialect=DIALECT, schema_translate_map={None: schema},
                           render_schema_translate=True)).strip()  # fmt: skip


def _app(name: str) -> Table:
    return app_metadata.tables[name]


def _type(col: Column[Any]) -> str:
    return str(DIALECT.type_compiler_instance.process(col.type))


def _schema(schema: str) -> str:
    return f"IF SCHEMA_ID(N'{schema}') IS NULL\n    EXEC('CREATE SCHEMA {Q(schema)}');\nGO"


def _add_column(table: Table, name: str, schema: str) -> str:
    col = table.c[name]
    if name == "isActive":
        # Existing rows are the current versions.
        spec = f"BIT NOT NULL CONSTRAINT {Q(f'DF_{table.name}_isActive')} DEFAULT 1"
    else:
        # Added as NULL so existing rows stay valid; the pipeline fills every new row.
        spec = f"{_type(col)} NULL"
    target = f"{Q(schema)}.{Q(table.name)}"
    return (f"IF COL_LENGTH(N'{schema}.{table.name}', N'{name}') IS NULL\n"
            f"    ALTER TABLE {target} ADD {Q(name)} {spec};\nGO")  # fmt: skip


def _create(table: Table, schema: str) -> str:
    ddl = _compile(CreateTable(table), schema)
    return f"IF OBJECT_ID(N'{schema}.{table.name}', N'U') IS NULL\n{ddl};\nGO"


def _indexes(table: Table, schema: str) -> list[str]:
    out = []
    for ix in sorted(table.indexes, key=lambda i: i.name or ""):
        ddl = _compile(CreateIndex(ix), schema)
        target = f"{schema}.{table.name}"
        out.append(f"IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'{ix.name}' "
                   f"AND object_id = OBJECT_ID(N'{target}'))\n    {ddl};\nGO")  # fmt: skip
    return out


def changes() -> str:
    parts = [HEADER, "-- Changes to the team's data model diagram for the pipeline (Phase 9).",
             "-- Safe to run more than once.", "", _schema(APP_SCHEMA), ""]  # fmt: skip
    parts += ["-- 1. New tables ------------------------------------------------------------", ""]
    for name in NEW_TABLES:
        parts += [f"-- {name}: {TABLE_DOCS[name]}", _create(_app(name), APP_SCHEMA),
                  *_indexes(_app(name), APP_SCHEMA), ""]  # fmt: skip
    parts += ["-- 2. Added columns ----------------------------------------------------------", ""]
    for name, cols in ADDED_COLUMNS.items():
        parts += [f"-- {name}"] + [_add_column(_app(name), c, APP_SCHEMA) for c in cols] + [""]
    parts += ["-- 3. Indexes for the BFF's reads ---------------------------------------------", ""]
    for name in sorted(ADDED_COLUMNS):
        parts += _indexes(_app(name), APP_SCHEMA)
    refs = ", ".join(f"N'{r}'" for r in REPLACED_REFERENCES)
    parts += [
        "",
        "-- 4. Foreign keys to tables the pipeline replaced -------------------------------",
        "-- " + ", ".join(REPLACED_REFERENCES) + " are no longer built. Columns that referenced",
        "-- them (TranscriptsId, runId, News.ArticleId) now hold pipeline ids: transcript document",
        "-- id, pipeline run id and news article id. Drop those foreign keys. List them with:",
        "--",
        "-- SELECT fk.name AS constraint_name, OBJECT_SCHEMA_NAME(fk.parent_object_id) AS",
        "--        table_schema, OBJECT_NAME(fk.parent_object_id) AS table_name,",
        "--        OBJECT_NAME(fk.referenced_object_id) AS referenced_table",
        "-- FROM sys.foreign_keys fk",
        f"-- WHERE OBJECT_NAME(fk.referenced_object_id) IN ({refs});",
        "--",
        "-- then for each row:",
        "--   ALTER TABLE [<table_schema>].[<table_name>] DROP CONSTRAINT [<constraint_name>];",
        "",
        "-- 5. Content format (no DDL) ----------------------------------------------------",
        "-- Sources columns (KeyInsights.source, StrategicRisk.sources, Activities.sources,",
        "-- FollowUpQuestions.sources, Trend.DataSources, CompanyMetricDetail.DataSources) hold",
        '-- JSON: [{"title": "...", "url": "...", "date": "YYYY-MM-DD"}]. KeyInsights.link is the',
        "-- first url. MatrixData.accession, filed_date and context_or_dimension hold JSON lists.",
        "",
    ]
    return "\n".join(parts)


def full(md: MetaData, schema: str, what: str,
         added: dict[str, list[str]] | None = None) -> str:  # fmt: skip
    parts = [HEADER, f"-- {what}", "", _schema(schema), ""]
    for table in md.sorted_tables:
        new_cols = [_add_column(table, c, schema) for c in (added or {}).get(table.name, [])]
        parts += [_create(table, schema), *new_cols, *_indexes(table, schema), ""]
    return "\n".join(parts)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    outputs = {
        "app_schema_changes.sql": changes(),
        "app_schema_full.sql": full(app_metadata, APP_SCHEMA, "Every application table the "
                                    "pipeline writes, in dependency order. Tables owned by the "
                                    "application (Users, UserHistory, ...) are not included."),
        "pipeline_schema_full.sql": full(pipeline_metadata, PIPELINE_SCHEMA, "The pipeline's own "
                                         "tables (raw facts, documents, LLM cache, runs, DQ). The "
                                         "BFF does not read them.", PIPELINE_ADDED_COLUMNS),
    }  # fmt: skip
    for name, text in outputs.items():
        (OUT / name).write_text(text, encoding="utf-8")
        print(f"wrote deploy/sql/{name}")


if __name__ == "__main__":
    main()
