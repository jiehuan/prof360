"""Write deploy/sql/bff_user_tables.sql: SQL Server DDL for the user-state tables (D-048).

    python -m p360_bff.ddl

Tables go in the app schema of config/azure.yaml (default environment). Every statement checks
first, so the script can run twice. The columns are inferred from the diagram's table names and
are to be confirmed against the team's DDL (user_tables.py).
"""

from __future__ import annotations

from typing import Any

from sqlalchemy.dialects import mssql
from sqlalchemy.schema import CreateIndex, CreateTable

from p360_bff.settings import REPO
from p360_bff.user_tables import user_metadata
from uw_pipeline.clients.db import load_azure_config

OUT = REPO / "deploy" / "sql" / "bff_user_tables.sql"
DIALECT: Any = mssql.dialect(deprecate_large_types=True)  # type: ignore[no-untyped-call]
DIALECT.server_version_info = (15,)


def ddl() -> str:
    az = load_azure_config(REPO / "config")
    schema = az.azure_sql.environments[az.default_env].app_schema
    parts = [
        "-- Generated by `python -m p360_bff.ddl` from bff/src/p360_bff/user_tables.py.",
        "-- Do not edit; change the table definitions and regenerate. Target: Azure SQL.",
        f"-- User-state tables of the BFF (D-048) in the app schema [{schema}]. Columns are",
        "-- inferred from the data model diagram's table names: TO CONFIRM with the team.",
        "",
    ]
    for table in user_metadata.sorted_tables:

        def compile_(element: Any) -> str:
            return str(
                element.compile(
                    dialect=DIALECT,
                    schema_translate_map={None: schema},
                    render_schema_translate=True,
                )
            ).strip()

        parts += [
            f"IF OBJECT_ID(N'{schema}.{table.name}', N'U') IS NULL",
            compile_(CreateTable(table)) + ";",
            "GO",
        ]
        for index in sorted(table.indexes, key=lambda i: str(i.name)):
            parts += [
                f"IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'{index.name}' "
                f"AND object_id = OBJECT_ID(N'{schema}.{table.name}'))",
                compile_(CreateIndex(index)) + ";",
                "GO",
            ]
        parts.append("")
    return "\n".join(parts)


def main() -> None:
    OUT.write_text(ddl(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
